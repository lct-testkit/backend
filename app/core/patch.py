"""Общие проверки тел PATCH.

В PATCH «поле не передано» и «поле передано как null» — разные вещи: первое значит «не
менять», второе — «очистить». Для обязательных колонок (NOT NULL) очистка невозможна, и
явный `null` доходил до БД, где превращался в 500. Валидатор отвечает 422 с именем поля ещё
на границе API. Подключается как `@field_validator("поле", mode="before")`: для не
переданных полей pydantic его не вызывает, поэтому пропуск поля остаётся допустимым.
"""

from __future__ import annotations

from typing import Any


def reject_null(value: Any) -> Any:
    if value is None:
        raise ValueError("Обязательное поле нельзя очистить: чтобы не менять, не передавайте его")
    return value
